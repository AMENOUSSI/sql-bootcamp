/*
SELECT and WHERE are the most fundamental SQL statement and you will
find yoursel using them often!
The WHERE statement allows us tospecify conditions on columns for rows to be returned.

Basic syntax example:

SELECT column1, column2
FROM table
WHERE conditions;

- The conditions are used to filter the rows returned from the SELECT statement.

. Comparison Operators
	. =: Equal 
	. <: Less than
	. >: Greater than
	. <=: Less than or equal to
	. >=: Greater than or equal to
	. <> or != : Not equal to

Logical Operators
	Allow us to combine multiple comparison operators
	. AND
	. OR
	. NOT
*/



